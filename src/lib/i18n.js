export function getLang() { return lang; }
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'es';
  try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
